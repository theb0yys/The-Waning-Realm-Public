using System;
using System.Diagnostics;
using System.IO;
using System.Xml.Serialization;
using TAOM_CheatPanel.Settings;
using TAOM_CheatPanel.Runtime;
using TaleWorlds.Core;
using TaleWorlds.CampaignSystem;
using TaleWorlds.CampaignSystem.CharacterDevelopment;

internal static class ProgressionChecks
{
    internal static void Run(Action<bool,string> check)
    {
        var cfg = new CheatPanelSettings();
        CheatPanelSettings.Instance = cfg;
        check(!cfg.TakeBothPerks && cfg.PlayerXpMultiplier == 1 && cfg.ExtraAttributePointsPerLevel == 0 && cfg.ExtraFocusPointsPerLevel == 0, "Inert progression defaults");
        var xml = new XmlSerializer(typeof(CheatPanelSettings));
        var old = (CheatPanelSettings)xml.Deserialize(new StringReader("<CheatPanelSettings><DefaultGold>321</DefaultGold></CheatPanelSettings>"));
        check(old.DefaultGold == 321 && !old.TakeBothPerks && old.PlayerXpMultiplier == 1, "Old XML preserved with inert new defaults");
        cfg.TakeBothPerks = true; cfg.PlayerXpMultiplier = 3; cfg.ExtraAttributePointsPerLevel = 2; cfg.ExtraFocusPointsPerLevel = 4;
        var text = new StringWriter(); xml.Serialize(text, cfg);
        var saved = (CheatPanelSettings)xml.Deserialize(new StringReader(text.ToString()));
        check(saved.TakeBothPerks && saved.PlayerXpMultiplier == 3 && saved.ExtraAttributePointsPerLevel == 2 && saved.ExtraFocusPointsPerLevel == 4, "Progression XML round trip");
        check(ProgressionRules.ScaleXp(10, true, true, cfg) == 30, "Main hero XP scaled");
        check(ProgressionRules.ScaleXp(10, false, true, cfg) == 10, "NPC XP untouched");
        check(ProgressionRules.ScaleXp(10, true, false, cfg) == 10, "Explicit cheat XP untouched");
        check(ProgressionRules.ScaleXp(-10, true, true, cfg) == -10 && ProgressionRules.ScaleXp(0, true, true, cfg) == 0, "Nonpositive XP untouched");
        check(float.IsNaN(ProgressionRules.ScaleXp(float.NaN, true, true, cfg)), "NaN not transformed");
        check(float.IsPositiveInfinity(ProgressionRules.ScaleXp(float.PositiveInfinity, true, true, cfg)), "Infinity not transformed");
        check(ProgressionRules.ScaleXp(float.MaxValue, true, true, cfg) == float.MaxValue, "No multiplication overflow");
        cfg.Enabled = false;
        check(ProgressionRules.ScaleXp(10, true, true, cfg) == 10, "Master overrides XP");
        cfg.Enabled = true; cfg.PlayerXpMultiplier = int.MaxValue;
        check(ProgressionRules.ScaleXp(10, true, true, cfg) == 100, "Multiplier upper clamp");
        cfg.PlayerXpMultiplier = -5;
        check(ProgressionRules.ScaleXp(10, true, true, cfg) == 10, "Multiplier lower clamp");
        check(ProgressionRules.AddBonusPoints(int.MaxValue - 2, 10) == int.MaxValue && ProgressionRules.AddBonusPoints(5, -1) == 5, "Bonus point saturation and lower clamp");
        var skill = new SkillObject(); var otherSkill = new SkillObject();
        var a = new PerkObject { Skill = skill, RequiredSkillValue = 25 };
        var b = new PerkObject { Skill = skill, RequiredSkillValue = 25, AlternativePerk = a }; a.AlternativePerk = b;
        var locked = new PerkObject { Skill = skill, RequiredSkillValue = 100, AlternativePerk = a };
        var singleton = new PerkObject { Skill = skill, RequiredSkillValue = 1 };
        PerkObject.All.AddRange(new[] { a, b, locked, singleton, null });
        var hero = new Hero(); Hero.MainHero = hero; hero.Skills[skill] = 25;
        var npc = new Hero(); npc.Skills[skill] = 300;
        var behavior = new ProgressionCheatBehavior(); behavior.RegisterEvents();
        cfg.TakeBothPerks = false;
        CampaignEvents.OnSessionLaunchedEvent.Handler(new CampaignGameStarter());
        check(hero.Perks.Count == 0, "Disabled session does not grant perks");
        cfg.TakeBothPerks = true;
        CampaignEvents.HourlyTickEvent.Handler();
        check(hero.Perks.Contains(a) && hero.Perks.Contains(b) && !hero.Perks.Contains(locked) && !hero.Perks.Contains(singleton), "Enable catches up only earned paired tiers");
        check(hero.HeroDeveloper.Writes == 2, "Reentrant perk event terminates without duplicate write");
        int reads = hero.Reads;
        CampaignEvents.HourlyTickEvent.Handler();
        check(hero.HeroDeveloper.Writes == 2, "Hourly reconciliation never duplicates perk grants");
        cfg.TakeBothPerks = false; hero.Perks.Clear(); cfg.TakeBothPerks = true;
        CampaignEvents.HourlyTickEvent.Handler();
        check(hero.Perks.Count == 2, "Off/on between hourly callbacks still reconciles");
        CampaignEvents.HeroGainedSkill.Handler(npc, skill, 1, true);
        check(npc.Perks.Count == 0, "NPC skill event ignored");
        hero.Perks.Clear(); cfg.Enabled = false;
        CampaignEvents.HeroGainedSkill.Handler(hero, skill, 1, true);
        check(hero.Perks.Count == 0, "Master overrides perk option");
        cfg.Enabled = true;
        CampaignEvents.HeroGainedSkill.Handler(hero, otherSkill, 1, true);
        check(hero.Perks.Count == 0, "Skill event scopes to changed skill");
        CampaignEvents.HeroGainedSkill.Handler(hero, skill, 1, true);
        check(hero.Perks.Count == 2, "Skill event grants earned pair");
        CampaignEvents.HeroLevelledUp.Handler(hero, true);
        check(hero.HeroDeveloper.UnspentAttributePoints == 2 && hero.HeroDeveloper.UnspentFocusPoints == 4, "Level awards configured extra points once");
        CampaignEvents.HeroLevelledUp.Handler(npc, true);
        check(npc.HeroDeveloper.UnspentFocusPoints == 0, "NPC level unchanged");
        cfg.Enabled = false; CampaignEvents.HeroLevelledUp.Handler(hero, true);
        check(hero.HeroDeveloper.UnspentFocusPoints == 4, "Disabled level unchanged");
        cfg.Enabled = true;
        CampaignEvents.OnSessionLaunchedEvent.Handler(new CampaignGameStarter());
        check(hero.HeroDeveloper.UnspentFocusPoints == 4 && hero.Perks.Count == 2, "Session reload does not award retrospective points or duplicate perks");
        PerkObject.All.Clear();
        for (int i = 0; i < 10000; i++) PerkObject.All.Add(new PerkObject { Skill = skill, RequiredSkillValue = 1000, AlternativePerk = a });
        reads = hero.Reads;
        CampaignEvents.HeroGainedSkill.Handler(hero, skill, 1, true);
        check(hero.Reads - reads == 10000, "One linear pass for 10000 synthetic perks");
        cfg.PlayerXpMultiplier = 2;
        float sink = 0; var watch = Stopwatch.StartNew();
        for (int i = 0; i < 1000000; i++) sink += ProgressionRules.ScaleXp(1, true, true, cfg);
        watch.Stop();
        check(sink == 2000000 && watch.ElapsedMilliseconds < 5000, "Million-call XP guard below conservative 5-second regression ceiling");
        Console.WriteLine("XP guard: 1000000 calls, " + watch.ElapsedMilliseconds + " ms; threshold 5000 ms; " + Environment.Version + "; " + Environment.OSVersion);
    }
}
